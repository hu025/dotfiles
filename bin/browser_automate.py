def main():
    parser = argparse.ArgumentParser(
        description="browser_automate — 浏览器自动化高级封装（browser-use + HTTP fallback）",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
示例：
  %(prog)s "打开 baidu.com 搜索 Hermes Agent 提取前 5 条结果"
  %(prog)s --task extract "https://news.ycombinator.com"
  %(prog)s --task search "Python 教程"
  %(prog)s --browser-status
""",
    )
    parser.add_argument("task_pos", nargs="?", help="自然语言任务描述（与 --template 互斥）")
    parser.add_argument("--template", choices=["extract", "search", "monitor"],
                        help="使用内置任务模板")
    parser.add_argument("--url", help="模板任务的 URL（extract/monitor）")
    parser.add_argument("--query", help="搜索关键词（search 任务）")
    parser.add_argument("--engine", default="duckduckgo",
                        choices=["duckduckgo", "bing", "google"],
                        help="搜索引擎（默认 duckduckgo）")
    parser.add_argument("--no-browser-use", action="store_true",
                        help="跳过 browser-use，强制 HTTP fallback")
    parser.add_argument("--browser-status", action="store_true",
                        help="显示浏览器环境诊断信息")
    parser.add_argument("--timeout", type=int, default=180, help="browser-use 超时秒数")
    parser.add_argument("--json", action="store_true", help="以 JSON 格式输出")

    args = parser.parse_args()

    # 诊断模式
    if args.browser_status:
        ba = BrowserAutomate()
        print(json.dumps(ba.status(), indent=2, ensure_ascii=False))
        return

    # 构造任务
    if args.template:
        if args.template == "extract":
            if not args.url:
                print("❌ extract 任务需要 --url", file=sys.stderr)
                sys.exit(2)
            task_str = TEMPLATES["extract"].format(url=args.url)
        elif args.template == "search":
            if not args.query:
                print("❌ search 任务需要 --query", file=sys.stderr)
                sys.exit(2)
            task_str = TEMPLATES["search"].format(query=args.query, engine=args.engine)
        elif args.template == "monitor":
            if not args.url:
                print("❌ monitor 任务需要 --url", file=sys.stderr)
                sys.exit(2)
            task_str = TEMPLATES["monitor"].format(
                url=args.url, fields="价格", threshold="涨跌幅 > 5%"
            )
        else:
            task_str = args.template
    elif args.task_pos:
        task_str = args.task_pos
    else:
        parser.print_help()
        sys.exit(1)

    # 执行
    ba = BrowserAutomate(prefer_browser_use=not args.no_browser_use)
    result = ba.run(task_str, timeout_s=args.timeout)

    # 输出
    if args.json:
        print(json.dumps(result, indent=2, ensure_ascii=False))
    else:
        if result.get("ok"):
            print(f"✅ Backend: {result.get('backend')}")
            if "stdout" in result:
                print(result["stdout"])
            elif "title" in result:
                print(f"📄 {result.get('title')}")
                if result.get("description"):
                    print(f"   {result['description']}")
                if result.get("text_blocks"):
                    print("\n📝 内容片段：")
                    for i, block in enumerate(result["text_blocks"][:5], 1):
                        print(f"   [{i}] {block[:200]}")
            elif "results" in result:
                print(f"🔍 {result.get('query')} ({result.get('engine')})")
                for i, r in enumerate(result["results"], 1):
                    print(f"\n   [{i}] {r['title']}")
                    print(f"       {r['url']}")
                    if r.get("snippet"):
                        print(f"       {r['snippet'][:150]}")
        else:
            print(f"❌ 失败: {result.get('error', 'unknown')}", file=sys.stderr)
            sys.exit(1)


if __name__ == "__main__":
    main()
