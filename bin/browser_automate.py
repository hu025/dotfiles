def http_fetch(url: str, timeout_s: int = 15, headers: Optional[Dict] = None) -> Dict[str, Any]:
    """纯 HTTP GET，提取 title 和正文（HTML）"""
    default_headers = {
        "User-Agent": "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 "
                      "(KHTML, like Gecko) Chrome/120.0 Safari/537.36",
        "Accept": "text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8",
        "Accept-Language": "zh-CN,zh;q=0.9,en;q=0.8",
    }
    default_headers.update(headers or {})

    req = urllib.request.Request(url, headers=default_headers)
    try:
        with urllib.request.urlopen(req, timeout=timeout_s) as r:
            raw = r.read()
            content_type = r.headers.get("Content-Type", "")
            encoding = "utf-8"
            if "charset=" in content_type:
                m = re.search(r"charset=([\w-]+)", content_type)
                if m:
                    encoding = m.group(1)
            try:
                html = raw.decode(encoding, errors="replace")
            except LookupError:
                html = raw.decode("utf-8", errors="replace")
            return {
                "ok": True,
                "url": url,
                "status": r.status,
                "content_type": content_type,
                "html": html,
                "size": len(raw),
            }
    except Exception as e:
        return {"ok": False, "url": url, "error": str(e)}


def extract_title(html: str) -> str:
    m = re.search(r"<title[^>]*>(.*?)</title>", html, re.DOTALL | re.IGNORECASE)
    return m.group(1).strip() if m else ""


def extract_meta_description(html: str) -> str:
    m = re.search(
        r'<meta[^>]+name=["\']description["\'][^>]+content=["\']([^"\']+)["\']',
        html, re.IGNORECASE
    )
    if not m:
        m = re.search(
            r'<meta[^>]+content=["\']([^"\']+)["\'][^>]+name=["\']description["\']',
            html, re.IGNORECASE
        )
    return m.group(1).strip() if m else ""


def extract_text_blocks(html: str, max_chars: int = 5000) -> List[str]:
    """简易正文提取：去掉脚本/样式/HTML 标签，取连续文字块"""
    # 去掉 script/style
    html = re.sub(r"<script\b[^>]*>.*?</script>", " ", html, flags=re.DOTALL | re.IGNORECASE)
    html = re.sub(r"<style\b[^>]*>.*?</style>", " ", html, flags=re.DOTALL | re.IGNORECASE)
    html = re.sub(r"<!--.*?-->", " ", html, flags=re.DOTALL)
    # 提取段落/标题
    blocks = re.findall(r"<(?:p|h\d|li|article|section)[^>]*>(.*?)</\1>", html, re.DOTALL | re.IGNORECASE)
    if not blocks:
        blocks = re.findall(r">([^<>]{20,})<", html)
    cleaned = []
    for b in blocks:
        text = re.sub(r"<[^>]+>", " ", b)
        text = re.sub(r"\s+", " ", text).strip()
        if len(text) >= 10:
            cleaned.append(text)
    # 去重保序
    seen, out = set(), []
    for t in cleaned:
        if t not in seen:
            seen.add(t)
            out.append(t)
    return out[:50]


def run_http_fallback(task: str) -> Dict[str, Any]:
    """
    HTTP fallback：从任务描述里提取 URL，做简单的 title/meta/text 提取
    如果任务里没 URL，自动构造一个搜索 URL
    """
    log(f"[http-fallback] 任务: {task[:80]}...")

    # 从任务里抠 URL
    urls = re.findall(r"https?://[^\s\"'<>]+", task)

    if not urls:
        # 检测是否是搜索任务，构造搜索 URL
        search_match = re.search(r"搜索[「\"']?(.+?)[」\"']?", task)
        if not search_match:
            search_match = re.search(r"search\s+(?:for\s+)?[\"']?(.+?)[\"']?", task, re.IGNORECASE)
        if search_match:
            query = search_match.group(1).strip()
            urls = [f"https://duckduckgo.com/html/?q={urllib.parse.quote(query)}"]
            log(f"[http-fallback] 自动构造搜索 URL: query={query}")

    if not urls:
        return {
            "backend": "http-fallback",
            "ok": False,
            "error": "任务里没找到 URL 或搜索关键词，无法 fallback。",
            "hint": "browser-use 不可用时，fallback 仅支持已知 URL 或搜索关键词的纯 HTTP 抓取",
        }

    url = urls[0].rstrip(".,;:)")
    result = http_fetch(url)
    if not result["ok"]:
        return {"backend": "http-fallback", "ok": False, "error": result["error"], "url": url}

    title = extract_title(result["html"])
    desc = extract_meta_description(result["html"])
    blocks = extract_text_blocks(result["html"])

    # 搜索结果页的特殊处理
    if "duckduckgo.com" in url or "google.com/search" in url or "bing.com/search" in url:
        results = []
        for m in re.finditer(
            r'<a[^>]+(?:class="result__a"|href="(http[^"]+)"[^>]*>)[^<]*(?:<[^>]+>)*([^<]{5,100})',
            result["html"]
        ):
            href = m.group(1) if m.group(1) else ""
            title_text = re.sub(r"<[^>]+>", "", m.group(2)).strip()
            if href and title_text and href.startswith("http"):
                results.append({"title": title_text, "url": href})
                if len(results) >= 10:
                    break
        return {
            "backend": "http-fallback-search",
            "ok": True,
            "url": url,
            "results": results,
            "total": len(results),
            "note": "⚠️ 简化搜索结果，可能不完整。完整任务请修复 browser-use。",
        }

    return {
        "backend": "http-fallback",
        "ok": True,
        "url": url,
        "title": title,
        "description": desc,
        "text_blocks": blocks[:20],
        "text_blocks_total": len(blocks),
        "html_size": result["size"],
        "note": "⚠️ 这是简化 HTTP fallback，不执行 JS、不交互。完整任务请修复 browser-use。",
    }


