def log(msg: str, level: str = "INFO") -> None:
    """写日志到 LOG_FILE，同时输出到 stderr（不污染 stdout 数据）"""
    ts = time.strftime("%Y-%m-%d %H:%M:%S")
    line = f"[{ts}] [{level}] {msg}"
    try:
        with LOG_FILE.open("a", encoding="utf-8") as f:
            f.write(line + "\n")
    except Exception:
        pass
    if level in ("ERROR", "WARN") or os.getenv("BROWSER_AUTOMATE_VERBOSE"):
        print(line, file=sys.stderr)


def check_browser_use_available() -> bool:
    """检查 browser-use CLI 是否可用"""
    if not Path(BROWSER_USE_BIN).exists():
        log("browser-use CLI 不存在", "WARN")
        return False
    try:
        r = subprocess.run(
            [BROWSER_USE_BIN, "--version"],
            capture_output=True, text=True, timeout=5
        )
        return r.returncode == 0
    except Exception as e:
        log(f"browser-use 检查失败: {e}", "WARN")
        return False


def check_browser_use_doctor() -> Dict[str, Any]:
    """运行 browser-use doctor 获取健康状态（--json 不可用时退化为 --help 检测）"""
    try:
        # browser-use CLI 不支持 --json 选项，用 --help 探测 daemon 状态
        r = subprocess.run(
            [BROWSER_USE_BIN, "doctor"],
            capture_output=True, text=True, timeout=30
        )
        return {
            "healthy": r.returncode == 0,
            "exit_code": r.returncode,
            "stdout_tail": r.stdout[-500:] if r.stdout else "",
            "stderr_tail": r.stderr[-200:] if r.stderr else "",
        }
    except subprocess.TimeoutExpired:
        return {"healthy": False, "error": "doctor timeout"}
    except Exception as e:
        return {"healthy": False, "error": str(e)}


# ─────────────────────────────────────────────────────────────
# 后端 1: browser-use（主路径）
# ─────────────────────────────────────────────────────────────
def run_browser_use(task: str, timeout_s: int = 180) -> Dict[str, Any]:
    """
    调用 browser-use CLI 执行任务。
    方式：将 task 喂给 browser-use stdin，让其作为 simple task 执行。
    """
    log(f"[browser-use] 启动任务: {task[:80]}...")

    # browser-use CLI 的 stdin 模式：接收 Python 代码
    # 我们用 print 输出结果，简单包装
    code = f"""# Auto-generated by browser_automate.py
ensure_real_tab()
print({task!r})
"""

    try:
        r = subprocess.run(
            [BROWSER_USE_BIN],
            input=code,
            capture_output=True,
            text=True,
            timeout=timeout_s,
        )
        return {
            "backend": "browser-use",
            "ok": r.returncode == 0,
            "stdout": r.stdout.strip(),
            "stderr": r.stderr.strip()[-500:] if r.stderr else "",
            "exit_code": r.returncode,
        }
    except subprocess.TimeoutExpired:
        return {"backend": "browser-use", "ok": False, "error": f"timeout after {timeout_s}s"}
    except Exception as e:
        return {"backend": "browser-use", "ok": False, "error": str(e)}


