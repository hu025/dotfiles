# 主类
# ─────────────────────────────────────────────────────────────
class BrowserAutomate:
    """高级浏览器自动化封装"""

    def __init__(self, prefer_browser_use: bool = True, verbose: bool = False):
        self.prefer_browser_use = prefer_browser_use
        self.verbose = verbose
        self.browser_use_ok = check_browser_use_available() if prefer_browser_use else False
        log(f"BrowserAutomate 初始化: browser_use={'可用' if self.browser_use_ok else '不可用'}")

    def run(self, task: str, timeout_s: int = 180) -> Dict[str, Any]:
        """执行任务，自动选择 backend"""
        if self.browser_use_ok:
            result = run_browser_use(task, timeout_s=timeout_s)
            if result.get("ok"):
                return result
            log(f"browser-use 失败，尝试 fallback: {result.get('error', '?')}", "WARN")
        # fallback
        return run_http_fallback(task)

    def extract(self, url: str, instruction: str = "") -> Dict[str, Any]:
        """提取网页信息（优先 browser-use）"""
        task = f"打开 {url}，{instruction or '提取标题、描述、主要内容'}"
        return self.run(task)

    def search(self, query: str, engine: str = "duckduckgo", n: int = 5) -> Dict[str, Any]:
        """搜索并提取结果"""
        if engine == "duckduckgo":
            url = f"https://duckduckgo.com/html/?q={urllib.parse.quote(query)}"
        elif engine == "bing":
            url = f"https://www.bing.com/search?q={urllib.parse.quote(query)}"
        else:
            url = f"https://www.google.com/search?q={urllib.parse.quote(query)}"

        # 先用 http 抓搜索页
        result = http_fetch(url)
        if not result["ok"]:
            return {"ok": False, "backend": "http-search", "error": result["error"]}

        # 提取搜索结果（duckduckgo html 版）
        html = result["html"]
        items = []
        if "duckduckgo" in url:
            # 匹配结果链接和标题
            for m in re.finditer(
                r'<a[^>]+class="result__a"[^>]+href="([^"]+)"[^>]*>(.*?)</a>',
                html, re.DOTALL
            ):
                href = m.group(1)
                title = re.sub(r"<[^>]+>", "", m.group(2)).strip()
                # 提取摘要
                snippet_m = re.search(
                    rf'result__snippet[^>]*>(.*?)</a>',
                    html[m.end():m.end() + 3000], re.DOTALL
                )
                snippet = re.sub(r"<[^>]+>", " ", snippet_m.group(1)).strip() if snippet_m else ""
                if title and href.startswith("http"):
                    items.append({"title": title, "url": href, "snippet": snippet[:200]})
                if len(items) >= n:
                    break
        return {
            "ok": True,
            "backend": "http-search",
            "query": query,
            "engine": engine,
            "results": items,
            "total": len(items),
        }

    def status(self) -> Dict[str, Any]:
        """浏览器环境诊断"""
        status = {
            "browser_use_cli": self.browser_use_ok,
            "browser_use_path": BROWSER_USE_BIN,
            "fallback_available": True,
        }
        if self.browser_use_ok:
            status["doctor"] = check_browser_use_doctor()
        return status


